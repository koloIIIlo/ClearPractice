/** Interleaved by tag, so consecutive days rarely share one. */
function interleave(): DailyPrompt[] {
  const tags = Object.keys(BY_TAG) as PromptTag[];
  const longest = Math.max(...tags.map((t) => BY_TAG[t].length));
  const out: Omit<DailyPrompt, "id">[] = [];
  for (let i = 0; i < longest; i += 1) for (const tag of tags) if (i < BY_TAG[tag].length) out.push({ text: BY_TAG[tag][i], tag });
  return out.map((p, i) => ({ id: `daily-${String(i + 1).padStart(3, "0")}`, ...p }));
}

export const DAILY_PROMPTS: readonly DailyPrompt[] = interleave();
