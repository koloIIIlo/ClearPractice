import { Bot, Gauge, NotebookPen, Ruler, type LucideIcon } from "lucide-react";
import type { EvidenceSource, MetricValue } from "@/lib/ipc/schemas";
import { cn } from "@/lib/utils";

/**
 * Where a displayed observation came from (§6 Session review, §11).
 * These describe the evidence source, never a confidence percentage.
 */
const SOURCES: Record<EvidenceSource, { label: string; icon: LucideIcon; hint: string }> = {
  measured: { label: "Measured", icon: Ruler, hint: "Calculated directly from the saved recording." },
  estimated: { label: "Estimated", icon: Gauge, hint: "Derived from speech detection or the transcript. Can be wrong." },
  note: { label: "Your note", icon: NotebookPen, hint: "Something you wrote or confirmed." },
  ai: { label: "AI suggestion", icon: Bot, hint: "Generated by the coaching provider from your transcript text." },
};

export function EvidenceLabel({ source, className }: { source: EvidenceSource; className?: string }) {
  const { label, icon: Icon, hint } = SOURCES[source];
  return (
    <span
      title={hint}
      className={cn(
        "inline-flex items-center gap-1 rounded-md border px-1.5 py-0.5 text-xs font-medium text-muted-foreground",
        className,
      )}
    >
      <Icon aria-hidden className="size-3.5" />
      {label}
    </span>
  );
}

/** A metric that may be unavailable — shown as such, never as zero (§6 Progress, §11). */
export function MetricRow({ metric }: { metric: MetricValue }) {
  return (
    <div className="flex items-start justify-between gap-4 py-2">
      <div className="min-w-0">
        <div className="text-meta text-muted-foreground">{metric.label}</div>
        {metric.value === null ? (
          <div className="text-meta">
            <span className="font-medium">Unavailable</span>
            {metric.unavailableReason && <span className="text-muted-foreground"> · {metric.unavailableReason}</span>}
          </div>
        ) : (
          <div className="font-medium tabular-nums">
            {metric.value}
            {metric.unit && <span className="ml-1 text-meta font-normal text-muted-foreground">{metric.unit}</span>}
          </div>
        )}
      </div>
      <EvidenceLabel source={metric.source} className="shrink-0" />
    </div>
  );
}
