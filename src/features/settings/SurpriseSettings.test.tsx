import { screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { expect, it, vi } from "vitest";
import { renderWithApp } from "@/test/render";
import { createMockClient } from "@/lib/ipc/mock-client";
import { DEFAULT_PREFERENCES, Preferences } from "@/lib/ipc/schemas";
import { SurpriseSettings } from "./SurpriseSettings";
it("keeps old profiles off and requests permission only on explicit opt-in", async () => {
  const { surpriseEnabled, surpriseStart, surpriseEnd, surpriseDays, surpriseNotifications, ...old } = DEFAULT_PREFERENCES;
  expect(Preferences.parse(old)).toEqual(DEFAULT_PREFERENCES);
  expect(Preferences.safeParse({ ...DEFAULT_PREFERENCES, surpriseStart: "18:00", surpriseEnd: "09:00" }).success).toBe(false);
  expect(Preferences.safeParse({ ...DEFAULT_PREFERENCES, surpriseStart: "+1:00" }).success).toBe(false);
  const client = createMockClient();
  const permission = vi.spyOn(client, "requestNotificationPermission").mockResolvedValueOnce(true).mockResolvedValueOnce(false);
  const save = vi.spyOn(client, "setPreferences");
  const user = userEvent.setup();
  renderWithApp(<SurpriseSettings />, { client });
  expect(permission).not.toHaveBeenCalled();
  await user.click(await screen.findByRole("switch", { name: "Surprise prompts" }));
  await waitFor(() => expect(save).toHaveBeenLastCalledWith(expect.objectContaining({ surpriseEnabled: true })));
  await user.click(screen.getByRole("checkbox", { name: "Show as a Windows notification" }));
  await waitFor(() => expect(save).toHaveBeenLastCalledWith(expect.objectContaining({ surpriseNotifications: true })));
  await user.click(screen.getByRole("checkbox", { name: "Show as a Windows notification" }));
  await waitFor(() => expect(save).toHaveBeenLastCalledWith(expect.objectContaining({ surpriseNotifications: false })));
  expect(permission).toHaveBeenCalledTimes(1);
  await user.click(screen.getByRole("checkbox", { name: "Show as a Windows notification" }));
  expect(await screen.findByRole("status")).toHaveTextContent("permission was not granted");
  expect(screen.getByRole("checkbox")).not.toBeChecked();
  await user.click(screen.getByRole("button", { name: "sunday" }));
  await waitFor(() => expect(save).toHaveBeenLastCalledWith(expect.objectContaining({ surpriseDays: expect.arrayContaining(["sunday"]) })));
});
